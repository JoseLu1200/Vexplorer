// Diagnóstico: recorre unos pasos y guarda una captura por paso. Uso: node scripts/recorrido.mjs <base> <carpeta> [ancho] [alto] [tema]
import { chromium } from "playwright-core";
import fs from "node:fs";
const [, , base = "http://localhost:4417/", out = "recorrido", w = "1440", h = "900", theme = ""] = process.argv;
fs.mkdirSync(out, { recursive: true });
const browser = await chromium.launch({ executablePath: "C:/Program Files/Google/Chrome/Application/chrome.exe", headless: true, args: ["--use-angle=swiftshader", "--enable-unsafe-swiftshader"] });
const page = await browser.newPage({ viewport: { width: Number(w), height: Number(h) } });
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errors.push(m.text()); });
const shot = async (name) => { await page.screenshot({ path: `${out}/${name}.png`, fullPage: true }); console.log(name, await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1 ? "SCROLL-H" : "ok")); };
await page.goto(base + (theme ? `?theme=${theme}` : ""));
await page.waitForSelector("[data-status=needs_review]", { timeout: 15000 });
await page.waitForTimeout(2500);
await page.locator("[data-plan] button[aria-label^='piezas_espesor_desconocido']").first().click();
await page.waitForSelector("[aria-label='Clases de dato'] >> visible=true", { timeout: 15000 });
await page.waitForTimeout(500);
await shot("plano");
await page.locator("tr[data-row] button:has-text('desconocido')").first().click().catch(() => {});
await page.waitForTimeout(400);
await shot("plano-completar");
await page.locator("nav[aria-label='Pantallas del plano'] a:has-text('Análisis') >> visible=true").first().click();
await page.waitForTimeout(700);
await shot("analisis-replay");
await page.goto(base + (theme ? `?theme=${theme}` : "") + "#/");
await page.waitForTimeout(3500);
await page.locator("[data-plan] button[aria-label^='piezas_completo']").first().click();
await page.waitForTimeout(1500);
await shot("biblioteca");
console.log(errors.length ? errors.join("\n") : "sin errores");
await browser.close();
